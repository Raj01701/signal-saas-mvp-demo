def lord_pairs(
    pairs: list[tuple[int, int]],
    rule_id: str,
    name: str,
    description: str,
    summary: Callable[[int, int], str],
    category: str,
    sources: list[dict[str, Any]],
    names: dict[tuple[int, int], str] | None = None,
    domains: list[str] | None = None,
) -> dict[str, Any]:
    instances = []
    for a, b in pairs:
        lagna = next(L for L in range(12) if lord(L, a) != lord(L, b))
        x, y = lord(lagna, a), lord(lagna, b)
        # Positive: the two lords conjoined; also a chart with them opposite each other.
        together = next(s for s in range(12) if LORDS[s] not in (x, y))
        rest = next(
            r
            for r in range(12)
            if r not in (together, (together + 6) % 12) and LORDS[r] not in (x, y)
        )
        positives = [spec(lagna, {x: together, y: together}, rest)]
        assert associated(x, together, y, together)
        opposite = (together + 6) % 12
        if LORDS[opposite] not in (x, y):
            positives.append(spec(lagna, {x: together, y: opposite}, rest))
            assert associated(x, together, y, opposite)
        # Negative: adjacent signs (no graha aspects the 2nd or 12th), no exchange.
        sx = next(
            s
            for s in range(12)
            if LORDS[s] != y and LORDS[(s + 1) % 12] != x and not associated(x, s, y, (s + 1) % 12)
        )
        negative = spec(lagna, {x: sx, y: (sx + 1) % 12}, rest)
        overrides: dict[str, Any] = {}
        if names and (a, b) in names:
            overrides["name"] = names[(a, b)]
        effects = {
            "domains": domains or ["status", "career"],
            "polarity": "positive",
            "strength": "major" if category == "raja" else "moderate",
            "summary": summary(a, b),
        }
        overrides["effects"] = effects
        instances.append(
            {
                "params": {"a": a, "b": b},
                "overrides": overrides,
                "tests": {"positive": positives, "negative": [negative]},
            }
        )
    return {
        "defaults": {"category": category, "school": "parashari", "provenance": "classical"},
        "families": [
            {
                "template": {
                    "id": rule_id,
                    "name": name,
                    "description": description,
                    "when": "lord({a}) != lord({b}) and associated(lord({a}), lord({b}))",
                    "participants": "[lord({a}), lord({b})]",
                    "notes": (
                        "Association means conjunction, mutual graha drishti or sign "
                        "exchange. A single planet owning both houses is not counted here "
                        "(see raja.yogakaraka)."
                    ),
                    "sources": sources,
                },
                "instances": instances,
            }
        ],
    }


