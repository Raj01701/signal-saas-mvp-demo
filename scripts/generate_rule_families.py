def ordinal(n: int) -> str:
    suffix = "th" if 10 <= n % 100 <= 20 else {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suffix}"


def _matters(a: int, b: int) -> str:
    return (
        f"the {ordinal(a)} house ({HOUSE_MATTERS[a]}) and the {ordinal(b)} house "
        f"({HOUSE_MATTERS[b]})"
    )


def lord(lagna: int, house: int) -> str:
    return LORDS[(lagna + house - 1) % 12]


def sign_of_house(lagna: int, house: int) -> int:
    return (lagna + house - 1) % 12


def aspects(planet: str, from_sign: int, to_sign: int) -> bool:
    return any((from_sign + h - 1) % 12 == to_sign for h in ASPECTS[planet])


def associated(a: str, sa: int, b: str, sb: int) -> bool:
    """Conjunction, mutual aspect or exchange of two different planets."""
    if a == b:
        return False
    conj = sa == sb
    mutual = aspects(a, sa, sb) and aspects(b, sb, sa)
    swap = LORDS[sa] == b and LORDS[sb] == a
    return conj or mutual or swap


def spec(lagna: int, placements: dict[str, int], rest: int, **extra: Any) -> dict[str, Any]:
    out: dict[str, Any] = {"lagna": SIGNS[lagna]}
    for planet, sign in placements.items():
        out[planet] = SIGNS[sign] if isinstance(sign, int) else sign
    out["rest"] = SIGNS[rest]
    out.update(extra)
    return out


def citation(text: str, **fields: Any) -> dict[str, Any]:
    return {"text": text, **fields, "verified": False}


