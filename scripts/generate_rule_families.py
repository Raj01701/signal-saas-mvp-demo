def conjunctions() -> dict[str, Any]:
    families = []
    for size, label, source in (
        (2, "dwigraha", citation("brihat_jataka", edition="sastri", chapter=14)),
        (
            3,
            "trigraha",
            citation(
                "saravali", edition="santhanam", locator="Chapter on three-planet conjunctions"
            ),
        ),
    ):
        instances = []
        for group in combinations(SEVEN, size):
            others = [p for p in SEVEN if p not in group]
            sign, rest = 4, 9
            positive = spec(0, dict.fromkeys(group, sign), rest)
            negative = spec(0, {**dict.fromkeys(group, sign), group[-1]: (sign + 1) % 12}, rest)
            extra = spec(0, {**dict.fromkeys(group, sign), others[0]: sign}, rest)
            names = " and ".join(p.title() for p in group)
            meaning = "; ".join(f"{p.title()}: {SIGNIFICATIONS[p]}" for p in group)
            condition = " and ".join(f"conjunct({group[0]}, {p})" for p in group[1:])
            condition += f" and count(only(companions({group[0]}), seven)) == {size - 1}"
            instances.append(
                {
                    "params": {
                        "key": "_".join(group),
                        "names": names,
                        "condition": condition,
                        "members": "[" + ", ".join(group) + "]",
                    },
                    "overrides": {
                        "effects": {
                            "domains": ["character"],
                            "polarity": "mixed",
                            "strength": "minor",
                            "summary": (
                                f"The significations of the planets blend ({meaning}); "
                                "the outcome depends on their dignity and on the house "
                                "and sign they occupy."
                            ),
                        },
                    },
                    "tests": {"positive": [positive], "negative": [negative, extra]},
                }
            )
        families.append(
            {
                "template": {
                    "id": f"conjunction.{label}_{{key}}",
                    "name": f"{label.title()} Yoga ({{names}})",
                    "description": (
                        "{names} occupy the same sign, with no other of the seven planets "
                        f"there ({label.title()} yoga)."
                    ),
                    "when": "{condition}",
                    "participants": "{members}",
                    "sources": [source],
                },
                "instances": instances,
            }
        )
    return {
        "defaults": {"category": "conjunction", "school": "parashari", "provenance": "classical"},
        "families": families,
    }


