def _dump(document: dict[str, Any]) -> str:
    class Dumper(yaml.SafeDumper):
        pass

    def represent_dict(dumper: yaml.SafeDumper, data: dict[str, Any]) -> yaml.Node:
        flow = "lagna" in data or set(data) <= {"text", "edition", "chapter", "locator", "verified"}
        return dumper.represent_mapping("tag:yaml.org,2002:map", data.items(), flow_style=flow)

    def represent_list(dumper: yaml.SafeDumper, data: list[Any]) -> yaml.Node:
        flow = all(isinstance(x, (str, int)) and len(str(x)) < 20 for x in data)
        return dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=flow)

    Dumper.add_representer(dict, represent_dict)
    Dumper.add_representer(list, represent_list)
    return yaml.dump(document, Dumper=Dumper, sort_keys=False, width=100, allow_unicode=True)


